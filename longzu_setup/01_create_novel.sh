#!/usr/bin/env bash
# 01_create_novel.sh —— 创建《龙族：同级生》长篇书
# 纯本地 DB 写入，不调用 LLM。防重跑：同名书已存在则中止。
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv/Scripts/python.exe
TITLE="龙族：同级生"

if $PY cli.py novel list 2>/dev/null | grep -Fq "$TITLE"; then
  echo "[中止] 已存在同名书《$TITLE》，请勿重跑。" >&2
  exit 1
fi

SYNOPSIS=$(cat <<'EOF'
2009年夏，十八岁的路明非收到一封来自卡塞尔学院的录取通知——一所深藏在美国中西部、以屠龙为毕生事业的古怪大学。与此同时，另一名少年也坐上了开往芝加哥的列车。他将与路明非同期入学，一起熬过3E考试、自由一日与社团战争，在狮心会与学生会的角力之间寻找自己的位置。
然而平静的校园生活只是表象。三峡的江水之下沉睡着两千年未醒的青铜城，龙王正在苏醒，秘党的千年战争即将把这一届新生推上最前线。少年们还不知道，等待他们的是荣耀、牺牲，以及无法回头的成长。
EOF
)

WORLD_INTRO=$(cat <<'EOF'
【世界底色】
现代人类文明并非地球上的第一代文明。远古时代，龙族曾是世界的主宰，以基因与言灵统治万物；人类在混血种（人龙混血后裔）的带领下推翻龙族，史称屠龙战争。龙王们被杀死或封印，龙骨与遗产散落世界各地，但龙族从未真正消亡——它们只是沉睡，等待苏醒。

【秘党与卡塞尔】
屠龙者的传承在隐秘中延续千年，其正统组织是“秘党”。秘党开办的卡塞尔学院坐落在美国中西部，表面是普通私立大学，实则是全球混血种的最高学府与战争中枢：一面培养学生，一面由执行部在全球范围内猎杀复苏的龙类。学院由校董会出资、昂热校长主持，内部学生自治团体林立，最强的是狮心会与学生会。

【混血种与言灵】
混血种按血统浓度分为S、A、B、C、D五级，S级数十年一出。高阶混血种可以通过咏唱龙文发动“言灵”——干涉物理世界的超自然能力，从强化听觉到操纵火焰、时间不等，序列号越高越危险，使用过度会反噬心智，甚至堕落为死侍。混血种越强大，越能听见同类灵魂深处的孤独，称为“血之哀”。

【当前局势】
故事开始的2009年，沉寂已久的龙类苏醒迹象频现。青铜与火之王诺顿与其双生兄弟康斯坦丁封葬于长江三峡的青铜城中，即将苏醒；加图索等古老家族各怀心思；远在日本，蛇岐八家与白王的阴影也在蠢动。卡塞尔迎来了史上罕见的一届新生——S级路明非，以及与他同期入学的原创主角。
EOF
)

$PY cli.py novel create \
  --title "$TITLE" \
  --genre "都市奇幻 · 学院 · 青春热血" \
  --synopsis "$SYNOPSIS" \
  --world-intro "$WORLD_INTRO"

echo "---- 当前书单 ----"
$PY cli.py novel list
