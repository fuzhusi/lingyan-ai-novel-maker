  --personality "$P" --speaking-style "$S" --appearance "$A" \
  --background "$BK" --motivation "$M" --arc "$R"

P="温柔、开朗、带点调皮的姐姐型专员，爱拿叶胜打趣，真到绝境时却坚韧到超越人体极限；对陌生人也亲切（面试时笑着纠正明非的日语）。"
S="声音轻柔、日式礼貌，爱笑，会开玩笑；战斗通讯里冷静简短，只在以为通讯断了的时候才说真心话。"
A="年轻女孩，与叶胜同款墨绿制服套裙，领口塞玫瑰红蕾丝领巾，日本风，笑起来有姐姐般的亲切感。"
BK="日本出身的卡塞尔执行部专员，与叶胜同期入校、是固定搭档和恋人（入校时叶胜十八岁，游泳最好）。2009年春与叶胜在丽晶酒店共同面试（“我叫酒德亚纪”），后同赴夔门。青铜城内她勾着虚脱的叶胜游过倾墙，超越潜水极限独自浮上水面，把铜罐推上救生艇说出“那是叶胜……抢回来的……”，随后被水下的存在拖走。"
M="和叶胜一起完成任务、一起回去；嘴上说“你死在水下我可不救你”。"
R="原著走向：与叶胜同葬夔门，是全书第一场正面展示给读者的执行部死亡，江南式“人怎么忽然就死了”。在本书中，她第2章给浑身是血的沈拾裹毯子，卷尾那条毯子被沈拾烧掉一角——她是他在这个世界收到的第一份善意，也是他没救成的第一个人。"
$PY cli.py character create --novel "$NID" --name "酒德亚纪" \
  --personality "$P" --speaking-style "$S" --appearance "$A" \
