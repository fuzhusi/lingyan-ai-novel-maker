# ========== 4. 大纲：卷 + 18 章 ==========
VOL=$($PY cli.py outline create --novel "$NID" --type volume --title "第一卷 火之晨曦·同级生" \
  --summary "2009年春，跨书任务者沈拾落进仕兰中学容器林舟体内，与路明非同班同期入学卡塞尔。满级意识困在1级身体里，他本想做完最后一单下班，却被叶胜亚纪之死逼成第一个想改剧本的人。18章。" 2>/dev/null)
echo "$VOL"
VID=$(echo "$VOL" | grep -oE '\[[0-9]+\]' | head -1 | tr -d '[]')
echo "卷节点 ID=$VID"

oc() { # $1 标题  $2 摘要
  "$PY" cli.py outline create --novel "$NID" --type chapter --parent "$VID" --title "$1" --summary "$2" 2>/dev/null
}

