BK="卡塞尔学院执行部专员，言灵·蛇（信息感知：以蛇为媒介读取龙文与环境信息，海量信息灌入大脑如太平洋灌入长江，极度耗损体力）。十八岁从中国到美国入校，游泳全班最好，第二年就和酒德亚纪成了固定搭档兼恋人。2009年春作为面试官来华，在丽晶酒店主持17人面试（三问），随即与亚纪被调往四川夔门行动。"
M="完成任务、带着亚纪活着回去；在那之前，把每一次任务都干漂亮。"
R="原著走向（夔门/青铜城）：他放蛇读出青铜城全图、取得铜罐，最终永留江底城中；亚纪把罐子送出后也被拖走。两人的死被昂热对全校隐瞒（“叶胜和亚纪离开了我们”）。在本书中，他第2章就与沈拾结下善缘（看出砖头角度不对、把他叫进面试名单），是沈拾清单上第一项遗憾，也是他决心“改剧本”的直接原因。"
