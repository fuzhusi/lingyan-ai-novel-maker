#!/usr/bin/env bash
# 06_protagonist.sh —— 原创主角卡 + 金手指规则世界观 + 创作罗盘
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv/Scripts/python.exe
NID=3

# 防重跑：已存在主角卡则中止
EXISTS=$($PY -c "import sqlite3;print(sqlite3.connect('data.db').execute(\"select count(*) from characters where novel_id=$NID and name like '沈拾%'\").fetchone()[0])")
if [ "$EXISTS" != "0" ]; then
  echo "[中止] 主角卡已存在，请勿重跑。" >&2
  exit 1
fi

P=$(cat <<'EOF'
三层结构。表层：随和、嘴欠、能躺着绝不坐着的老油条，把“不摇碧莲”当生存美学，对社团战争、舞会、生死任务都带着“我见过”的倦怠和调侃，像在二倍速重刷一部老剧。中层：职业、冷静、手稳心硬，十几年异人桩功和多个书战场练出的执行力，对危险有生理级的预判，真出事时全场他最可靠。里层：疲惫、空、不敢投入感情——他知道自己注定翻页走人；院长死后，“回家”对他只剩惯性。命门式弱点是“孤儿雷达”：见不得小孩和弱者像他小时候一样没人管，对“本可以救却没救”的遗憾毫无免疫力，这是油滑外壳上唯一的裂缝。
EOF
)
S=$(cat <<'EOF'
现代口语，爱接茬、自嘲、插科打诨，被问来历一律用“上份工作”“以前认识个人”含糊带过，越紧张越贫。对路明非是损友加老哥的口吻，嘴上嫌弃、手上护着；对零话最少、最不绕弯；对昂热这类老狐狸礼貌打太极、滴水不漏。极少数认真时刻，语气会忽然变得很平、很旧，像一个比在场所有人都老的人。
EOF
)
A=$(cat <<'EOF'
十八岁少年的身体（林舟），中等偏高、瘦削结实，不是楚子航那种锋锐的好看，而是不起眼却耐看的类型。最异常的是动作：站立时重心永远微微下沉（异人桩功本能），走路几乎没声音，接东西从不会失手，在人群里像一把裹着布的刀。入学时穿林舟遗物里最旧的几件衣服，手心的茧位置不像混血种，倒像常年握刀磨出来的。
EOF
)
B=$(cat <<'EOF'
蓝星华裔，孤儿院长大，院长是他全部的亲情。不知因何成为跨书旅人，以弥补书中人的“遗憾”为业，辗转多个世界。上一本书是异人世界：身份是哪都通的编外临时工，练的是通用异人功夫——一门护体炁功、雷法的发力法门、市井短打与冷兵器，没有八奇技那种天花板绝学；异人最值钱的听劲、气机预判和发力方式被他刻进了神经。某次任务间隙他拼力打听到蓝星的消息：孤儿院已拆迁，院长已故。从此他只剩“做完最后一本回家”的惯性，尽管家里已无人等他。最后一站落进《龙族》：任务规则允许他在遗憾弥补完成后回归，并可带走书中一人。他落进卡塞尔本届录取生林舟的身体——林舟也是孤儿，低阶混血种的母亲早亡，接到录取通知的当夜死于一场血脉觉醒事故，沈拾在他断气的瞬间睁眼，枕边是拆了一半的录取通知。他顶着林舟的身份入学，脑子里装着全书剧情：白帝城、北京、东京的每一场死亡他都知道。
EOF
)
M=$(cat <<'EOF'
表层：完成遗憾清单、顺利“下班”回家（纯惯性）。中层：替原主林舟活下去，还这条捡来的命的债；护住路明非这届新生，让某些死亡别照剧本发生。深层（他自己不肯承认）：在一个注定要离开的世界里，确认自己还会不会为别人的生死心疼；并最终给零一个没有实验舱、没有龙王的普通世界，也给自己找一个“有人等”的去处。
EOF
)
R=$(cat <<'EOF'
从“把世界当书、把人当NPC、做完就走”的过客，被路明非的赤诚、楚子航的执念和零的沉默一步步逼回人间：从嘲笑遗憾的人，变成弥补遗憾最凶的人。前期以为自己是看戏的，中期发现自己上了台，后期才明白他从来不是观众。终局归途开启、蓝星空无一人，他带零回家，完成“无家可归者成为别人的家”的转变。暗线：这个剧本之外的变量终将被路鸣泽与昂热识破——他与魔鬼的谈判、与零号羁绊的正面碰撞，是他最大的危机，也是零这条线的终极考验。
EOF
)
$PY cli.py character create --novel "$NID" --name "沈拾（林舟）" \
  --personality "$P" --speaking-style "$S" --appearance "$A" \
  --background "$B" --motivation "$M" --arc "$R"

# ---- 金手指规则世界观（后续每章生成的“宪法”） ----
C=$(cat <<'EOF'
【主角沈拾的穿越与能力规则——作者级设定，写作时必须严格遵守】

一、身份。沈拾是蓝星出身的跨书任务者，多次穿书，《龙族》是他最后一站。他落进本届卡塞尔新生林舟体内：林舟为低阶混血种遗孤，接到录取通知当夜死于血脉觉醒事故，沈拾在其断气时睁眼顶替。对外他是林舟，"沈拾"这个真名这世界无人知晓。

二、信息层金手指：剧本全知 + 蝴蝶失效。他逐字记得自己穿越前读过的全部原著细节（人物命运、言灵、每场死亡与背叛）；但未出版的未来对他同样是黑的。规则：他每实质介入一次剧情，后续相关记忆就开始模糊、错位、失效，介入越深失效越快——龙族I阶段他近乎全知，白帝城后半瞎，越往后越要和所有人一样摸黑。写作上，先知不是爽点，是"提前到来的葬礼"：他笑着和每个人相处，心里清楚他们将怎么死。

三、能力层金手指：上一本书（异人世界）带过来的满级体术。哪都通编外临时工出身，有护体炁功、雷法发力、市井短打、冷兵器和听劲预判十几年苦功。但本世界没有"炁"这种能量：所有能量型手段过界即哑火，他也听不懂龙文、放不出任何言灵。剩下的纯粹是身体——桩功、反应、发力、杀人技，外加一把装备部定制的炼金冷兵器。入学体检数据为A级体术、龙血纯度却极低，血统与能力严重不匹配，诺玛标红、校方暗中关注。战力边界：学生第一梯队近战，斩龙侍如切菜；对龙王没有任何权能手段，元素与领域他破不了，龙王战只能当尖刀，胜负靠团队。

四、限制（无能量反噬，用别的锁）。1）身份锁：诺玛监控网、普通人保密法，他不能放开打，必须藏拙；2）藏不住：身体本能快过脑子，3E想装C级、自由一日却被迫露头；3）本地化：他的经验属于上本书，初见言灵对轰、龙鳞恢复力会吃瘪；4）蝴蝶效应吞掉先知红利；5）不能暴露穿越者身份——被路鸣泽这种层级识破是全书暗线节点，不是前期可以发生的事。

五、归途规则。任务是弥补书中遗憾；完成到约定程度，归途开启，他回蓝星，可带走书中一人。蓝星上唯一等他的孤儿院院长已故，归途那头空无一人。【作者级暗线，前期严禁点破，只许埋种子】他最终选中带走的人是零；他的真名、他的来历，将只告诉零一个人。零与零号/小魔鬼一系的羁绊是这条线最大的障碍，沈拾与路鸣泽未来必有一场关于零的谈判。

六、创作红线。沈拾不得抢占主角团的命定名场面：白帝城的成人礼属于路明非，北京的伤口属于楚子航；他可以在场、可以拼命、可以改变边缘，但核心悲剧的重量不许被他的战力抹平。他每改变一件事，必须产生真实可信的连锁后果。
EOF
)
$PY cli.py world create --novel "$NID" --category "主角设定" \
  --title "穿越者与归途规则（主角金手指）" --content "$C"

# ---- 创作罗盘 ----
INTENT=$(cat <<'EOF'
《龙族》同人、双主角结构。沈拾是蓝星孤儿出身的跨书任务者，带着上一世界（异人世界）被没收炁之后的满级体术，落进卡塞尔本届将死新生林舟体内，与路明非同期入学。他读过全书、记得每个人将怎样死去；最后一个任务是弥补遗憾，完成即可回蓝斯坦途——可世上唯一等他的孤儿院院长已经过世，归途空无一人。全书承诺：写一个把世界当书、把人当NPC的过客，怎样被路明非的赤诚、楚子航的执念和零的沉默重新教成一个会心疼的人；最终他带零离开，把“回家”重新定义为“有人等你”。基调学江南：青春的热烈与宿命的悲凉并存，幽默和牺牲只隔一层纸。先知不是爽点，是提前到来的葬礼；不许抢主角团的高光与悲剧，他改变的每件事都要有真实重量的后果。
EOF
)
FOCUS=$(cat <<'EOF'
第一卷·入学（龙族I前后）：沈拾顶替林舟身份，藏拙参加3E考试，与路明非结下损友情谊；自由一日被迫体术露头，成为两大社团与校方异常视线的焦点；与零完成两个“局外人”的初次辨认；路鸣泽第一次隐约察觉剧本之外有变量。卷末三峡白帝城：他以尖刀身份参战、只斩龙侍，不碰诺顿——路明非与老唐的成人礼完整保留；但康斯坦丁之死与老唐的觉醒，让他第一次动了“这剧本我要改”的念头。本卷终点：他从看戏的人，变成想动手的人。
EOF
)
$PY cli.py compass set --novel "$NID" --intent "$INTENT" --focus "$FOCUS"

echo "---- 完成 ----"
$PY cli.py character list --novel "$NID" | tail -3
$PY cli.py compass show --novel "$NID"
