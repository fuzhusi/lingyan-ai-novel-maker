#!/usr/bin/env bash
# 03_world.sh —— 为 novel 3《龙族：同级生》写入 30 条世界观设定
# 纯本地 DB 写入，不调用 LLM。防重跑：novel 3 已有世界观则中止。
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv/Scripts/python.exe
NID=3

COUNT=$($PY -c "import sqlite3;print(sqlite3.connect('data.db').execute('select count(*) from world_settings where novel_id=$NID').fetchone()[0])")
if [ "$COUNT" != "0" ]; then
  echo "[中止] novel $NID 已有 $COUNT 条世界观，请勿重跑。" >&2
  exit 1
fi

create_world() {
  # $1 类别 $2 标题 $3 正文
  "$PY" cli.py world create --novel "$NID" --category "$1" --title "$2" --content "$3"
}

