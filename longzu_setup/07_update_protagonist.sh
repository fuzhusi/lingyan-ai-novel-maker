#!/usr/bin/env bash
# 07_update_protagonist.sh —— 主角设定修订（v2）
# 1) 炁不没收：满级意识进1级身体，新身体重炼，修为随“重新有了牵挂”回归
# 2) 林舟=系统提前插空的独立个体，仕兰中学与路明非同班；穿越即死斗，记忆融合
# 3) 零是沈拾书外的本命角色：单女主，偏爱直接狂热，不搞选择题
# 4) 罗盘 focus 同步：第一卷拉长，入学前增加仕兰中学线，开场劲爆前置
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv/Scripts/python.exe
NID=3

# ---- 角色 55 性格 ----
P=$(cat <<'EOF'
三层结构。表层：随和、嘴欠、能躺着绝不坐着的老油条，把“不摇碧莲”当生存美学，对社团战争、舞会、生死任务都带着“我见过”的倦怠和调侃，像在二倍速重刷一部老剧。中层：职业、冷静、手稳心硬，十几年异人战场练出的意识和判断力，对危险有生理级的预判——哪怕现在这具身体跟不上，他的脑子和眼睛也始终是满级的。里层：疲惫、空、不敢投入感情，院长死后“回家”对他只剩惯性。命门式弱点有两个：一是“孤儿雷达”，见不得小孩和弱者像他小时候一样没人管；二是零——零是他在书外世界读《龙族》时最喜欢的角色，是他的本命，这点他从不讲理：谁动零他跟谁拼命，理智、任务、归途都可以不要。
EOF
)
$PY cli.py character update --id 55 --personality "$P"

# ---- 外貌（1级身体） ----
A=$(cat <<'EOF'
十八岁少年的身体（林舟），中等偏高，开局只是个普通高中生的单薄身板，毫无龙血痕迹。异常全在细节：站立时重心永远微微下沉（异人桩功本能），走路几乎没声音，接东西从不会失手，在人群里像一把裹着布的刀；手心旧茧的位置不像学生，倒像常年握刀磨出来的——而那具身体分明没有这样的过去。随着他用呼吸法重新炼炁，身形会以肉眼可见的速度沉实、利落起来。
EOF
)
$PY cli.py character update --id 55 --appearance "$A"

# ---- 背景（大改） ----
B=$(cat <<'EOF'
蓝星华裔，孤儿院长大，院长是他全部的亲情。不知因何成为跨书旅人，以弥补书中人的“遗憾”为业，辗转多个世界。上一本书是异人世界：身份是哪都通的编外临时工，练的是通用异人功夫——护体炁功、雷法发力、市井短打与冷兵器，没有八奇技那种天花板绝学，十几年苦功把听劲、预判和杀人技刻进了灵魂。某次任务间隙他拼力打听到蓝星的消息：孤儿院已拆迁，院长已故。他读《龙族》时最喜欢的角色是零——那时她还只是书里的人。
最后一站：系统提前在《龙族》世界“插空”放置了一个独立个体——林舟，仕兰中学高三学生，路明非的同班同学，一个在所有人眼里真实存在、却没有真正来历的少年。2009年高考结束的夏夜，城市边缘一场低阶龙类复苏的异常事件中，容器激活，沈拾被直接投进一场正在进行的猎杀：上一秒在书外，下一秒满嘴是血、手里只有半截砖头。林舟十八年的记忆、卡塞尔的录取资格，连同整部《龙族》的剧情，在他脑子里同时融合。他以林舟的身份活着，与路明非从同班同学做起，坐同一趟CC1000列车入学。
注意：炁没有被世界没收，而是这具新身体是空的——功法记忆、战斗意识、听劲经验完整带来，炁却要从一丝一缕重新炼起。他是满级的意识困在1级身体里。
EOF
)
$PY cli.py character update --id 55 --background "$B"

# ---- 动机 ----
M=$(cat <<'EOF'
表层：完成最后一单、下班“回家”（纯惯性，家里已无人等他）。中层：替林舟这个空壳真正活一次，护住仕兰中学就认识的路明非这届新生，让某些死亡别照剧本发生。深层：零。从书外的偏爱到书里的真人，他要把她带出黑天鹅港的影子、带出龙王和实验舱，去一个没有她档案的普通世界——这是他第一次为“自己想要”而不是任务去拼命。
EOF
)
$PY cli.py character update --id 55 --motivation "$M"

# ---- 弧光（微调） ----
R=$(cat <<'EOF'
从“把世界当书、把人当NPC、做完就走”的过客，被路明非的赤诚、楚子航的执念和零的沉默逼回人间。他的炁和他的心同步复苏：院长死后心如死灰时炁也停滞，当他重新有了想守护的人（零），功力才一层层回到身上——他变强，是因为他重新活过来了。前期以为自己是看戏的，中期发现自己上了台，后期才明白他从来不是观众。终局归途开启、蓝星空无一人，他带零回家，完成“无家可归者成为别人的家”。暗线：林舟这个系统造物为何存在、他这个变量终将被路鸣泽识破；他与魔鬼必有一场关于零的谈判。
EOF
)
$PY cli.py character update --id 55 --arc "$R"

# ---- 世界 60 金手指规则重写 ----
C=$(cat <<'EOF'
【主角沈拾的穿越与能力规则——作者级设定，写作时必须严格遵守】

一、身份。沈拾是蓝星孤儿出身的跨书任务者，多次穿书，《龙族》是他最后一站。系统提前在本世界“插空”放置了独立个体“林舟”：仕兰中学高三学生、路明非的同班同学，拥有合法的十八年人生与周围人的真实记忆，却没有真正来历，本质是世界允许存在的占位容器，自身没有强烈自我。2009年高考结束夏夜的一场低阶龙类异常中容器激活，沈拾被投入正在发生的猎杀，林舟的人生记忆与整部《龙族》剧情在他脑中融合。不存在两个灵魂争夺；沈拾要做的，是让这个空壳第一次真正活着。对外他是林舟，"沈拾"这个真名这世界无人知晓。

二、信息层金手指：剧本全知 + 蝴蝶失效。他记得穿越前读过的全部原著细节（人物命运、言灵、每场死亡与背叛），但未出版的未来对他同样是黑的。每实质介入一次剧情，后续相关记忆就模糊、错位、失效，介入越深失效越快——龙族I阶段近乎全知，白帝城后半瞎，越往后越要和所有人一样摸黑。先知不是爽点，是“提前到来的葬礼”。

三、能力层金手指：上一世界（异人世界，哪都通编外临时工）的满级意识 + 新身体从一重炼的炁。功法记忆、听劲、气机预判、杀人技的经验完整带来，但林舟这具身体是空的，炁要从一丝一缕重新修起——满级玩家困在1级号里。恢复阶段（节奏可微调）：第一卷入学至白帝城，炼回桩功与炁感、体能靠呼吸法急速强化，战力是“会杀人的普通人”，自由一日纯体术露头，白帝城只能当尖刀；第二卷北京，炁回中段，护体炁膜与雷法初阶发力可用，在言灵世界里开始显诡异；第三卷日本，炁近大成，可与高危言灵正面抗衡，但对龙王仍须团队与炼金装备。恢复原理是性命双修、神满气聚：他越是重新有了牵挂（零）、重新想活着，炁回来得越快；心如死灰时功力也停滞。他听不懂龙文、放不出言灵，诺玛体检显示低纯度血统配异常体术数据，入学即被标红。

四、限制（无能量反噬，用别的锁）。1）身份锁：诺玛监控网、普通人保密法，必须藏拙；2）藏不住：身体本能快过脑子；3）1级身体：开局意识碾压但体能拖后腿，越级会死；4）本地化：初见言灵对轰、龙鳞恢复力会吃瘪；5）蝴蝶效应吞掉先知红利；6）穿越者身份不能暴露，被路鸣泽这种层级识破是全书暗线节点。

五、归途与女主线。任务是弥补书中遗憾，完成到约定程度归途开启，他回蓝星、可带走书中一人；蓝星唯一等他的孤儿院院长已故，归途空无一人。零是他在书外读《龙族》时最喜欢的角色（本命），进入书内后从偏爱变成真爱——单女主，不设选择题。写法直接、狂热、不讲道理：全校都看得出他对零不正常，但他的好是平视不是俯视，不揭她的伤疤、不怜她、不安排她，只是认准了、护到底。真名与来历最终只告诉零。零与零号/小魔鬼一系的羁绊是最大障碍，沈拾与路鸣泽未来必有一场关于零的谈判。【作者级暗线，前期只埋种子，严禁点破】

六、创作红线。沈拾不得抢占主角团命定名场面：白帝城的成人礼属于路明非，北京的伤口属于楚子航；他可以在场、拼命、改变边缘，但核心悲剧的重量不许被战力抹平。他每改变一件事，必须产生真实可信的连锁后果。
EOF
)
$PY cli.py world update --id 60 --content "$C"

# ---- 罗盘 focus 重写（intent 原样保留重传） ----
INTENT=$(cat <<'EOF'
《龙族》同人、双主角结构。沈拾是蓝星孤儿出身的跨书任务者，上一世界是异人世界的哪都通临时工；他被投进系统预置的容器“林舟”——仕兰中学高三生、路明非的同班同学——在高考结束夏夜的一场龙类猎杀中醒来，林舟的记忆与整部《龙族》剧情同时融合。满级的异人意识困在1级身体里，炁要重新炼；他记得每个人将怎样死去，最后一单是弥补遗憾，完成即可回蓝星，可世上唯一等他的院长已经过世，归途空无一人。全书承诺：写一个把世界当书、把人当NPC的过客，怎样被路明非的赤诚、楚子航的执念和零的沉默重新教成一个会心疼的人；他的炁和他的心一起复苏，最终带零离开，把“回家”重新定义为“有人等你”。零是单女主、是他书外的本命，偏爱直接狂热。基调学江南：青春的热烈与宿命的悲凉并存，幽默和牺牲只隔一层纸。先知是提前到来的葬礼；不许抢主角团的高光与悲剧，每件改变都要有真实重量的后果。
EOF
)
FOCUS=$(cat <<'EOF'
第一卷·仕兰与卡塞尔（故事线拉长，入学前先写中国线）：1）2009高考结束夏夜，沈拾在城市边缘的龙类猎杀中睁眼，1级身体靠满级意识极限求生，记忆融合，发现自己是路明非的同班同学林舟；2）仕兰中学的夏天，他以老同学身份贴近路明非，亲历文学社、赵孟华、陈雯雯这条原著开篇线，明知这衰仔将失去什么却只能旁观和暗护；3）卡塞尔录取与诺诺面试，侧写在林舟身上第一次报警；4）与路明非同乘CC1000次列车，3E考试藏拙却因救人露异常；5）自由一日被迫体术露头，两大社团与守夜人争抢；6）他第一次见到零——书外的本命走到面前，狂热线启动但他选择平视；7）卷末白帝城，他以尖刀身份只斩龙侍不碰诺顿，路明非与老唐的成人礼完整保留；战后江堤上他动了“这剧本我要改”的念头，当夜路鸣泽第一次入梦，两个“不属于这世界的东西”短暂对视。
EOF
)
$PY cli.py compass set --novel "$NID" --intent "$INTENT" --focus "$FOCUS" 2>/dev/null

echo "---- 核验 ----"
.venv/Scripts/python.exe longzu_setup/04_export_review.py
