# 纯本地 DB 写入，不调用 LLM。防重跑：novel 3 已有角色则中止。
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv/Scripts/python.exe
NID=3

COUNT=$($PY -c "import sqlite3;print(sqlite3.connect('data.db').execute('select count(*) from characters where novel_id=$NID').fetchone()[0])")
if [ "$COUNT" != "0" ]; then
  echo "[中止] novel $NID 已有 $COUNT 个角色，请勿重跑。" >&2
  exit 1
fi

create_char() {
  # $1 名 $2 性格 $3 说话风格 $4 外貌 $5 背景 $6 动机 $7 弧光
  "$PY" cli.py character create --novel "$NID" --name "$1" \
    --personality "$2" --speaking-style "$3" --appearance "$4" \
    --background "$5" --motivation "$6" --arc "$7"
}

