# ---------------------------------------------------------------------------
# Regex patterns to remove/replace
# ---------------------------------------------------------------------------

BANNED_PATTERNS = [
    # 重复的"地"修饰
    (r"(\w)地(\w)地(\w)地", r"\1\2\3"),
    # 连续的形容词堆砌
    (r"(\w{2,4})的(\w{2,4})的(\w{2,4})的", r"\3"),
    # "一种X的感觉" -> "X"
    (r"一种(\w{2,6})的感觉", lambda m: m.group(1)),
    # "不由得/忍不住 + X起来" -> 去掉引导词。
    # 原规则只匹配"不由得"，但 Pass1 已把"不由得"换成"忍不住"，
    # 导致本规则永远打不中（死规则）；改为两种前导都匹配
    (r"(?:不由得|忍不住)(\w{2,4})起来", lambda m: m.group(1) + "起来"),
    # "在...下" 结构过多
    (r"在(\w{2,6})的(\w{2,6})下", r"\1\2"),
    # "对于...来说" -> 去掉
    (r"对于(\w{2,8})来说", r"\1"),
    # "就...而言" -> 去掉
    (r"就(\w{2,8})而言", r"\1"),
    # "在...方面" -> 去掉
    (r"在(\w{2,8})方面", r"\1"),
    # "从...来看" -> 去掉
    (r"从(\w{2,8})来看", r"\1"),
    # "据...了解" -> 去掉
    (r"据(\w{2,8})了解", r"\1"),
    # "通过...来" -> 直接动词
    (r"通过(\w{2,6})来(\w{2,4})", r"\1\2"),
    # "利用...来" -> 直接动词
    (r"利用(\w{2,6})来(\w{2,4})", r"\1\2"),
    # "借助...来" -> 直接动词
    (r"借助(\w{2,6})来(\w{2,4})", r"\1\2"),
    # "依靠...来" -> 直接动词
    (r"依靠(\w{2,6})来(\w{2,4})", r"\1\2"),
    # "凭借...来" -> 直接动词
    (r"凭借(\w{2,6})来(\w{2,4})", r"\1\2"),
    # "为了...而" -> 去掉"为了"
    (r"为了(\w{2,8})而(\w{2,4})", r"\1，\2"),
    # "因为...所以" -> 简化
    (r"因为(\w{2,8})，所以(\w{2,8})", r"\1，\2"),
    # "虽然...但是" -> 简化
    (r"虽然(\w{2,8})，但是(\w{2,8})", r"\1，但\2"),
    # "尽管...但是" -> 简化
    (r"尽管(\w{2,8})，但是(\w{2,8})", r"\1，但\2"),
    # "即使...也" -> 简化
    (r"即使(\w{2,8})，也(\w{2,8})", r"\1，\2"),
    # "无论...都" -> 简化
    (r"无论(\w{2,8})，都(\w{2,8})", r"\1，\2"),
    # "只要...就" -> 简化
    (r"只要(\w{2,8})，就(\w{2,8})", r"\1，\2"),
    # "只有...才" -> 简化
    (r"只有(\w{2,8})，才(\w{2,8})", r"\1，\2"),
    # "既然...就" -> 简化
    (r"既然(\w{2,8})，就(\w{2,8})", r"\1，\2"),
    # "不是X，而是Y" / "不是X，是Y" -> AI 典型对仗句式，打散。
    # 保留两侧信息（此前直接丢弃前半句，语义损失严重），
    # 用口语连接词替代"而是"，打破工整对仗
    (r"不是(\w{2,10})，而是(\w{2,10})", r"\1，其实\2"),
    (r"不是(\w{2,10})，是(\w{2,10})", r"\1，其实\2"),
]

